const catalogs: Record<SupportedLocale, MessageCatalog> = { en, fr, pt, ar };

interface I18nContextValue {
  locale: SupportedLocale;
  setLocale: (locale: SupportedLocale) => void;
  t: (key: MessageKey, variables?: Record<string, string | number>) => string;
}

const I18nContext = createContext<I18nContextValue | null>(null);

function interpolate(value: string, variables?: Record<string, string | number>): string {
  if (!variables) return value;
  return value.replace(/\{([^}]+)\}/g, (_match, name: string) => String(variables[name] ?? `{${name}}`));
}

export function I18nProvider({ children }: { children: ReactNode }) {
  const [locale, setLocaleState] = useState<SupportedLocale>(() => currentLocale());
  const value = useMemo<I18nContextValue>(() => ({
    locale,
    setLocale: (next) => { applyLocale(next); setLocaleState(next); },
    t: (key, variables) => interpolate((catalogs[locale] ?? en)[key] ?? en[key], variables),
  }), [locale]);
  return <I18nContext.Provider value={value}>{children}</I18nContext.Provider>;
}

export function useI18n(): I18nContextValue {
  const value = useContext(I18nContext);
  if (!value) throw new Error('I18N_PROVIDER_REQUIRED');
  return value;
}

