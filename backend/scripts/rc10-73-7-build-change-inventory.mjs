function groupsFor(path) {
  const groups = [];
  if (prompt1.has(path) || path.startsWith('release-evidence/local-environment/chromium-readiness/')) groups.push('Prompt 1');
  if (prompt3.has(path)) groups.push('Prompt 3');
  if (prompt4.has(path)) groups.push('Prompt 4');
  if (shared.has(path) || path.endsWith('tsconfig.tsbuildinfo')) groups.push('Shared verification');
  if (!groups.length) groups.push('Prompt 2');
  return groups;
}

const tracked = lines(git('diff', '--name-status')).map((line) => {
  const [status, ...parts] = line.split('\t');
  return { status, path: parts.at(-1) };
});
const untracked = lines(git('ls-files', '--others', '--exclude-standard')).map((path) => ({ status: 'A (untracked)', path }));
const files = [...tracked, ...untracked].sort((a, b) => a.path.localeCompare(b.path));
const rows = files.map((item) => `| ${item.status} | ${item.path} | ${groupsFor(item.path).join(', ')} |`);
const groupRows = ['Prompt 1', 'Prompt 2', 'Prompt 3', 'Prompt 4', 'Shared verification'].map((group) => {
  const matching = files.filter((item) => groupsFor(item.path).includes(group));
  return `| ${group} | ${matching.length} | ${matching.map((item) => `\`${item.path}\``).join('<br>')} |`;
});
