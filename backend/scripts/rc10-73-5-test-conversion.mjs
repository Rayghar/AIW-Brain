import assert from 'node:assert/strict';
import { readFileSync } from 'node:fs';
import { resolve, dirname } from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';
const root=resolve(dirname(fileURLToPath(import.meta.url)),'..');
const registry=JSON.parse(readFileSync(resolve(root,'data/rc10_73_5-github-conversion-registry.json'),'utf8'));
const patterns=JSON.parse(readFileSync(resolve(root,'data/rc10_73_5-pattern-dna2.1.json'),'utf8'));
const mod=await import(pathToFileURL(resolve(root,'packages/knowledge/dist/governedGithubKnowledgeConversion.js')).href);
const assessment=mod.assessGithubKnowledgeConversion({repositories:registry.repositories,patterns:patterns.records});
assert.equal(assessment.allowedForControlledPilot,true);
assert.equal(assessment.productionAccepted,false);
assert.equal(assessment.metrics.approvedRepositories,30);
assert.equal(assessment.metrics.recordsWithClaimLineage,328);
assert.equal(assessment.metrics.scoringCalibratedRecords,0);
const calm=registry.repositories.find((r)=>r.connectorId==='GH-FINOS-CALM');
assert.ok(calm);
assert.equal(mod.repositoryKnowledgeUseAllowed(calm,'descriptive'),true);
assert.equal(mod.repositoryKnowledgeUseAllowed(calm,'scoring'),false);
const layered=patterns.records.find((r)=>r.id==='STYLE-LAYERED');
assert.ok(layered);
assert.equal(mod.patternKnowledgeUseAllowed(layered.knowledgeAuthority,'composition'),true);
assert.equal(mod.patternKnowledgeUseAllowed(layered.knowledgeAuthority,'scoring'),false);
console.log(JSON.stringify({passed:true,tests:10,assessment},null,2));
