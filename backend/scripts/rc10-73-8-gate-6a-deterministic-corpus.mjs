function updatePeak(peak) {
  const memory = process.memoryUsage();
  peak.heapUsedBytes = Math.max(peak.heapUsedBytes, memory.heapUsed);
  peak.residentSetBytes = Math.max(peak.residentSetBytes, memory.rss);
  peak.externalBytes = Math.max(peak.externalBytes, memory.external);
}

async function* streamManifestFiles(manifestPath) {
  let search = '';
  let arrayStarted = false;
  let current = '';
  let depth = 0;
  let inString = false;
  let escaped = false;
  for await (const chunk of createReadStream(manifestPath, { encoding: 'utf8', highWaterMark: 1024 * 1024 })) {
    let text = `${search}${chunk}`;
    let start = 0;
    search = '';
    if (!arrayStarted) {
      const keyIndex = text.indexOf('"files"');
      if (keyIndex < 0) { search = text.slice(-32); continue; }
      const bracketIndex = text.indexOf('[', keyIndex + 7);
      if (bracketIndex < 0) { search = text.slice(keyIndex); continue; }
      arrayStarted = true;
      start = bracketIndex + 1;
    }
    for (let index = start; index < text.length; index += 1) {
      const character = text[index];
      if (depth === 0) {
        if (character === ']') return;
        if (character !== '{') continue;
        current = '{'; depth = 1; inString = false; escaped = false; continue;
      }
      current += character;
      if (inString) {
        if (escaped) escaped = false;
        else if (character === '\\') escaped = true;
        else if (character === '"') inString = false;
        continue;
      }
      if (character === '"') { inString = true; continue; }
      if (character === '{' || character === '[') depth += 1;
      else if (character === '}' || character === ']') depth -= 1;
      if (depth === 0) { yield JSON.parse(current); current = ''; }
    }
  }
  throw new Error(`FILES_ARRAY_NOT_TERMINATED:${manifestPath}`);
}

class UnionFind {
  constructor(size) { this.parent = Array.from({ length: size }, (_, index) => index); this.rank = new Uint8Array(size); }
  find(value) { let root = value; while (this.parent[root] !== root) root = this.parent[root]; while (this.parent[value] !== value) { const next = this.parent[value]; this.parent[value] = root; value = next; } return root; }
  union(left, right) { let a = this.find(left); let b = this.find(right); if (a === b) return; if (this.rank[a] < this.rank[b]) [a, b] = [b, a]; this.parent[b] = a; if (this.rank[a] === this.rank[b]) this.rank[a] += 1; }
}

async function processWithConcurrency(items, concurrency, processor) {
  const output = new Array(items.length);
  let cursor = 0;
  async function worker() {
    while (true) {
      const index = cursor; cursor += 1;
      if (index >= items.length) return;
      output[index] = await processor(items[index], index);
    }
  }
  await Promise.all(Array.from({ length: concurrency }, () => worker()));
  return output;
}

async function writeShards(prefix, records, idSelector) {
  const buckets = Array.from({ length: SHARD_COUNT }, () => []);
  for (const record of records) buckets[parseInt(sha256(idSelector(record)).slice(0, 2), 16) % SHARD_COUNT].push(record);
  const shards = [];
  for (let index = 0; index < SHARD_COUNT; index += 1) {
    buckets[index].sort((left, right) => idSelector(left).localeCompare(idSelector(right)));
    const name = `${prefix}-${index.toString(16).padStart(2, '0')}.ndjson`;
    const payload = buckets[index].map((record) => JSON.stringify(record)).join('\n') + (buckets[index].length ? '\n' : '');
    await writeFile(resolve(runRoot, name), payload, 'utf8');
    shards.push({ path: `knowledge-repository/AKR-0.10.73.8/candidate/gate-6a/deterministic-corpus-v1${runSuffix}/${name}`, records: buckets[index].length, bytes: Buffer.byteLength(payload), sha256: prefixedSha256(payload) });
  }
  return shards;
}

function countBy(items, selector) {
  const counts = {};
  for (const item of items) { const key = String(selector(item)); counts[key] = (counts[key] ?? 0) + 1; }
  return Object.fromEntries(Object.entries(counts).sort(([left], [right]) => left.localeCompare(right)));
}

