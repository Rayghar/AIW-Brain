#!/usr/bin/env node
import fs from 'node:fs';
import path from 'node:path';
const root = path.resolve(process.cwd(), 'apps/web/src');
const read = (file) => fs.readFileSync(path.join(root, file), 'utf8');
const checks = [];
const assert = (name, ok, detail='') => { checks.push({name,ok,detail}); if(!ok) process.exitCode=1; };
const nav = read('lib/roleNavigation.ts');
const shell = read('components/ShellNavRail.tsx');
const reviewer = read('components/ReviewerAssuranceStudio.tsx');
const security = read('components/SecurityWorkspace.tsx');
const runtime = read('components/PlatformRuntimeWorkspace.tsx');
const router = read('components/WorkspaceRouter.tsx');
const portfolio = read('components/PortfolioWorkspace.tsx');
const governance = read('components/GovernanceWorkspace.tsx');
const ops = read('components/OperationalIntelligenceWorkspace.tsx');
const admin = read('features/admin/AdminControlPlaneWorkspace.tsx');
const main = read('main.tsx');
assert('one role-task active-state contract', shell.includes('aiw.activeRoleTask') && shell.includes('taskExistsInRail'));
assert('enterprise destinations have explicit task states', nav.includes('Portfolio Home') && nav.includes('Standards Impact') && nav.includes('Release Impact'));
assert('reviewer evidence and audit are distinct', nav.includes('Evidence Ledger') && nav.includes('Review Audit') && reviewer.includes("taskFocus === 'evidence'") && reviewer.includes("taskFocus === 'audit'"));
assert('platform security is architecture-facing', security.includes('Security and trust') || security.includes('trust'), !security.includes('/api/platform/acceptance'));
assert('platform runtime is role-specific', router.includes('PlatformRuntimeWorkspace') && router.includes('roleId === "platform-architect"'));
assert('portfolio risk/reuse/release views are distinct', portfolio.includes("task === 'reuse'") && portfolio.includes("task === 'risks'") && portfolio.includes("task === 'releases'"));
assert('governance is progressive-disclosure based', governance.includes('governance-disclosure') && governance.includes('Priority governance findings'));
assert('operational workflow is lens-based', ops.includes("type OpsLens") && ops.includes('operational-lens-tabs'));
assert('pattern DNA list is paginated compactly', admin.includes('const patternPageSize = 10') && admin.includes('pattern-edit-disclosure'));
assert('curator scope is not labelled admin', admin.includes('Knowledge governance workspace'));
assert('release hardening stylesheet active', main.includes('rc10_65_2_role_journey_hardening.css'));
const failed = checks.filter((check) => !check.ok);
for (const check of checks) console.log(`${check.ok ? 'PASS' : 'FAIL'} ${check.name}${check.detail ? ` — ${check.detail}` : ''}`);
console.log(`rc.10.65.2 role journey hardening gate: ${checks.length - failed.length}/${checks.length} passed`);
if (failed.length) process.exit(1);
