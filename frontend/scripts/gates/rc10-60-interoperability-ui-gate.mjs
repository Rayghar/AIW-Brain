import { readFile } from 'node:fs/promises';
import { resolve, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';
const root = resolve(dirname(fileURLToPath(import.meta.url)), '../..');
const read = (p) => readFile(resolve(root,p),'utf8');
const checks=[]; const check=(name,ok,detail='')=>{checks.push({name,ok,detail});if(!ok)process.exitCode=1;};
const sdd=await read('apps/web/src/components/guided-delivery/SddDeliveryWorkspace.tsx');
const viewbook=await read('apps/web/src/features/canvas/ArchitectureViewbook.tsx');
const css=await read('apps/web/src/design-system/product-experience.css');
const modelling=await read('packages/modelling/src/architectureInteroperability.ts');
const layout=await read('packages/modelling/src/advancedLayout.ts');
const artifacts=await read('packages/artifacts/src/index.ts');
const pdf=await read('packages/artifacts/src/accessiblePdf.ts');
check('Architecture exchange is a first-class SDD delivery surface', sdd.includes('Architecture exchange &amp; delivery'));
check('Structurizr, CALM and LikeC4 downloads are visible', ['Structurizr DSL','Export CALM','LikeC4'].every((v)=>sdd.includes(v)));
check('Round-trip validation is user-invoked', sdd.includes('Validate round trip') || sdd.includes('round-trip'));
check('Accessible PDF is downloadable from the delivery room', sdd.includes('Download accessible PDF'));
check('Viewbook exposes deterministic auto layout', viewbook.includes('Auto layout') && viewbook.includes('applyAdvancedViewLayout'));
check('View-specific positions and orthogonal routes are applied', viewbook.includes('applyAdvancedViewLayout') && viewbook.includes('displayedProject') && layout.includes('orthogonal'));
check('Three exchange formats are implemented in the web distribution', ['structurizr-dsl','calm-json','likec4'].every((v)=>modelling.includes(`'${v}'`)));
check('Accessible PDF and architecture-as-code are in delivery pack', pdf.includes('system-design-description-accessible.pdf') && artifacts.includes('architecture-as-code'));
check('Exchange controls use responsive, contained product styling', css.includes('architecture-exchange') && css.includes('grid-template-columns'));
check('Canvas layout remains viewbook-centred', css.includes('canvas-page--viewbook-first'));
for(const item of checks) console.log(`${item.ok?'PASS':'FAIL'} ${item.name}${item.detail?` — ${item.detail}`:''}`);
if(process.exitCode) throw new Error('rc.10.60 frontend gate failed');
console.log(`PASS ${checks.length}/${checks.length} rc.10.60 frontend gates`);
