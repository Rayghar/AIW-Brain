import assert from 'node:assert/strict';
import {createProject} from './shared/projects-domain.js';
import {applyArchitectureCaseCommand,architectureCases,caseContextBasis,caseReviewBasis,caseObservationCurrent,caseObservationChanges,evaluateArchitectureCase} from './public/architecture-case.js';
import {renderFocusedCaseValidation,caseReviewWorklist,renderArchitectureCases} from './public/architecture-case-ui.js';

const at='2026-10-11T00:00:00.000Z';
const original=createProject({name:'Synthetic focused validation',template:'bank-payment'},'focused-case',at);
globalThis.window={location:{search:'?chapter=11&tab=validate&project=focused-case'}};
assert.match(renderFocusedCaseValidation(original,null),/case=new/);
let p=applyArchitectureCaseCommand(original,{type:'case.save',payload:{title:'Payment trace',purpose:'Review one selected payment obligation.',requirementIds:['REQ-001'],basis:caseContextBasis(original)}},at,'scope-architect').document;
let c=architectureCases(p)[0];
const observed={id:c.id,basis:caseReviewBasis(p,c),dimension:'Requirement correctness',outcome:'observed',reviewer:'Scope architect',notes:'Review the exact requirement intent.',reference:'REQ-001',reviewed:true};
p=applyArchitectureCaseCommand(p,{type:'case.observe',payload:observed},at,'scope-architect').document;c=architectureCases(p)[0];
assert(caseObservationCurrent(p,c,c.observations[0]));
assert(c.observations[0].dependencySnapshot.entries.length>0);
assert(c.observations[0].dependencySnapshot.entries.length<=600);
assert(c.observations[0].dependencySnapshot.entries.every(x=>!('record' in x)&&!('excerpt' in x)&&/^[0-9a-f]{64}$/.test(x.stamp)));
const unrelated=structuredClone(p);unrelated.artefacts.find(r=>r.id==='REQ-002').title+=' unrelated edit';
assert(caseObservationCurrent(unrelated,architectureCases(unrelated)[0],c.observations[0]));
assert.deepEqual(caseObservationChanges(unrelated,architectureCases(unrelated)[0],c.observations[0]).changes,[]);
const linked=structuredClone(p);linked.artefacts.find(r=>r.id==='REQ-001').title+=' revised';
const revised=architectureCases(linked)[0],difference=caseObservationChanges(linked,revised,c.observations[0]);
assert(!caseObservationCurrent(linked,revised,c.observations[0]));
assert(difference.available&&difference.changes.some(x=>x.kind==='requirement'&&x.key==='requirement:REQ-001'&&x.change==='changed'));
assert(difference.changes.find(x=>x.key==='requirement:REQ-001').fieldChanges.includes('title'));
const currentReport=evaluateArchitectureCase(p,{caseId:c.id}),changedReport=evaluateArchitectureCase(linked,{caseId:c.id});
assert.equal(currentReport.projectGate.ready,false);
assert.equal(changedReport.projectGate.ready,false);
assert.equal(currentReport.architectAssessment.status,'assessment-incomplete');
assert(caseReviewWorklist(currentReport).some(x=>x.key==='independent:Requirement correctness'));
assert(caseReviewWorklist(changedReport).some(x=>x.key==='assess:Requirement correctness'));
let ui=renderFocusedCaseValidation(linked,c.id);
assert.match(ui,/Focused case · Payment trace/);
assert.match(ui,/data-vx-case-select/);
assert.match(ui,/SDD.*separate gate/i);
assert.match(ui,/chapter=1&amp;tab=work&amp;artefact=REQ-001/);
assert.match(ui,/case=AC-001#ac-assessment/);
assert.doesNotMatch(ui,/Independent case finding recorded/);
ui=renderFocusedCaseValidation(linked,c.id,{history:'historical'});
assert.match(ui,/Changes since this observation/);
assert.match(ui,/changed · requirement/);
assert.match(ui,/Changed fields: title/);
assert.match(ui,/REQ-001/);
assert.match(renderArchitectureCases(linked,c.id),/Changes since this observation/);
const legacy=structuredClone(linked);delete architectureCases(legacy)[0].observations[0].dependencySnapshot;
assert.match(renderFocusedCaseValidation(legacy,c.id,{history:'historical'}),/previous dependency list was not retained/);
const hostile=structuredClone(linked);architectureCases(hostile)[0].observations[0].notes='<img src=x onerror=alert(1)>';
assert.doesNotMatch(renderFocusedCaseValidation(hostile,c.id,{history:'historical'}),/<img/);
console.log('Focused case Validate: scoped currency, bounded dependency changes, actionable links, independent review, separate SDD gate, and escaping passed.');
