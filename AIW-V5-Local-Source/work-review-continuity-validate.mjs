import assert from 'node:assert/strict';
import {withFinalReview} from './public/review-domain.js';
import {seedProject} from './public/requirements-domain.js';
import {createProject} from './shared/projects-domain.js';
import {createReviewStudio} from './public/review-ui.js';
import {createRuntimeStudio} from './public/runtime-ui.js';
globalThis.document={addEventListener(){},querySelector(){return null;}};
globalThis.window={addEventListener(){}};
const p=withFinalReview(seedProject()),before=JSON.stringify(p),moves=[];
const review=createReviewStudio({value:{document:p},command(){throw Error('Preview must never write a model command');}});
const state={chapter:11,tab:'work',selected:'api',reviewRequirement:'REQ-001',visible:['logical'],cursor:true};
review.bind({state,getNode:()=>({layer:'logical'}),render(){},setTab(tab){moves.push(tab);state.tab=tab;},toast(){}});
review.preview('assurance');
assert.deepEqual(moves,[],'a Work evidence suggestion keeps the same tab');
assert.equal(state.selected,'api','the selected architecture object remains selected');
const html=review.work();assert.match(html,/data-rv-proposal/);assert.match(html,/NOT SAVED/);assert.match(html,/Review and edit/);assert.match(html,/Open on Model/);assert.match(html,/Acceptance and verification remain separate/);
assert.ok(review.proposal.record.objectIds.includes('api'));
assert.equal(JSON.stringify(p),before,'preview neither adopts an action nor fabricates a review');
const runtime=createRuntimeStudio({value:{document:p}});
runtime.bind({state:{chapter:10,tab:'work',selected:'api-pod',environment:p.runtime.environments[0]?.id,visible:['deployment']},getNode:()=>null});
assert.match(runtime.work(),/data-rt-action="new-plan"[^>]*disabled=/);
assert.match(runtime.work(),/Every included asset already has a plan/);
const blank=withFinalReview(createProject({name:'Blank fixture',template:'blank'},'empty-work-fixture'));
const empty=createRuntimeStudio({value:{document:blank}});empty.bind({state:{chapter:10,tab:'work',selected:'project',visible:['deployment']},getNode:()=>null});
assert.match(empty.work(),/data-rt-action="new-plan"[^>]*disabled=/);assert.match(empty.work(),/Create an environment before adding a runtime plan/);
console.log(JSON.stringify({passed:3,checks:['Work evidence proposal remains unsaved in the selected object context, with explicit edit/dismiss/Model choices','No runtime plan editor is offered when every included asset already has a plan','Blank runtime Work explains its environment prerequisite beside the disabled action']},null,2));
