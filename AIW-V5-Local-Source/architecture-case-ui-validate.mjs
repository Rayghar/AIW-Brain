import assert from 'node:assert/strict';
import {createProject} from './shared/projects-domain.js';
import {applyArchitectureCaseCommand,caseContextBasis,caseReviewBasis,evaluateArchitectureCase} from './public/architecture-case.js';
import {renderArchitectureCases,renderArchitectureCaseDossier,caseConclusionForm,caseObservationForm} from './public/architecture-case-ui.js';

const at='2026-10-11T00:00:00.000Z',draft=createProject({name:'Synthetic payment dossier',template:'bank-payment'},'payment-dossier',at);
const p=applyArchitectureCaseCommand(draft,{type:'case.save',payload:{title:'Payment submission',purpose:'Follow payment recovery and verification.',requirementIds:['REQ-001'],basis:caseContextBasis(draft)}},at,'architect-one').document;
const c=p.finalReview.architectureCases[0],r=evaluateArchitectureCase(p,{caseId:c.id,requirementIds:c.requirementIds});
globalThis.window={location:{search:'?project=payment-dossier'}};
const page=renderArchitectureCases(p,c.id);
assert.match(page,/id="ac-readiness"/);
assert.match(page,/Whole project · separate gate/);
assert.match(page,/id="ac-project"/);
assert.match(page,/id="ac-evidence"/);
assert.match(page,/id="ac-choices"/);
assert.match(page,/PostgreSQL/);
assert.match(page,/MongoDB/);
assert.match(page,/ADR-001/);
assert.match(page,/Acknowledge a durable asynchronous handoff/);
assert.match(page,/source-use judgement/i);
assert.match(page,/id="ac-req-REQ-001"/);
assert.match(page,/data-rv-action="case-export-html"/);
assert.match(page,/data-rv-action="case-export"/);
assert.match(page,/Record case finding/);
assert.match(caseConclusionForm(c,r),/Whole-project SDD approval has its own gate/);
assert.match(caseObservationForm(c,'Evidence precision'),/sourceRightsReviewed/);
assert.doesNotMatch(caseObservationForm(c,'Overall usefulness'),/sourceRightsReviewed/);
assert.doesNotMatch(caseConclusionForm(c,r),/Support requires.*reviewed baseline/);
const html=renderArchitectureCaseDossier(p,c.id,{baseUrl:'https://aiw.example'});
for(const id of ['readiness','requirements','choices','evidence','finding','project'])assert.match(html,new RegExp(`id="${id}"`));
assert.match(html,/PostgreSQL/);
assert.match(html,/MongoDB/);
assert.match(html,/Architecture decisions/);
assert.match(html,/ADR-001/);
assert.match(html,/Keep the customer request synchronous/);
assert.match(html,/source-use judgement/i);
assert.match(html,/href="https:\/\/aiw\.example\/\?chapter=1/);
assert.match(html,/project=payment-dossier/);
assert.match(html,/No current architect-reviewed SDD baseline/);
assert.match(html,/Case support does not approve this gate/);
assert.match(html,/REQ-001/);
assert.doesNotMatch(html,/data-rv-action=/);
const edited=structuredClone(p),caseRecord=edited.finalReview.architectureCases[0];
edited.artefacts.find(x=>x.id==='REQ-001').provenance={sheet:'Payment source',sourceRow:42,cells:{description:'C42'},workbookHash:'synthetic-hash'};
caseRecord.history.at(-1).actor='scope-editor';
const basis=caseReviewBasis(edited,caseRecord);
caseRecord.observations.push({id:'rights-1',dimension:'Evidence precision',basis,outcome:'observed',actor:'scope-editor',reviewer:'Scope editor',notes:'Reviewed source use.',reference:'Original IDs',sourceRightsReviewed:true});
assert.match(renderArchitectureCases(edited,c.id),/architect acknowledgement; independent review pending/);
caseRecord.observations.push({id:'rights-2',dimension:'Evidence precision',basis,outcome:'gap',actor:'second-architect',reviewer:'Second architect',notes:'Use needs review.',reference:'Original IDs',sourceRightsReviewed:false});
assert.match(renderArchitectureCases(edited,c.id),/Source-use judgement · review needed/);
caseRecord.observations.push({id:'rights-3',dimension:'Evidence precision',basis,outcome:'observed',actor:'second-architect',reviewer:'Second architect',notes:'Reviewed permitted use.',reference:'Payment source row 42',sourceRightsReviewed:true});
const rights=renderArchitectureCases(edited,c.id);
assert.match(rights,/Source-use judgement · current independent architect acknowledgement/);
assert.match(rights,/REQ-001 · Accept a traceable payment instruction · revision not recorded · Payment source · row 42 · C42/);
const hostile=structuredClone(p);hostile.finalReview.architectureCases[0].title='<img src=x onerror=alert(1)>';
assert(!renderArchitectureCaseDossier(hostile,c.id).includes('<img'));
console.log('Architecture case UI: separated gates, anchored dossier, source trace, HTML export, and escaping passed.');
