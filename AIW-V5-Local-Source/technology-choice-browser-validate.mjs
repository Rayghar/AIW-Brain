// The Chapter 7 comparison keeps library discovery, architect judgement and a temporary
// quality scenario in their existing records and never silently selects a product.
import assert from 'node:assert/strict';
import {spawn} from 'node:child_process';
import {createRequire} from 'node:module';
import {rmSync} from 'node:fs';
import net from 'node:net';

const require=createRequire(import.meta.url);
const {chromium}=require(process.env.AIW_PLAYWRIGHT_MODULE||'playwright');
const port=await new Promise(resolve=>{const s=net.createServer().listen(0,'127.0.0.1',()=>{const p=s.address().port;s.close(()=>resolve(p))})});
const db='.aiw-local/technology-choice-browser-'+port+'.sqlite';
const server=spawn(process.execPath,['server.js','--port',String(port)],{env:{...process.env,AIW_LOCAL_DB:db,OPENAI_API_KEY:''},stdio:['ignore','pipe','inherit']});
process.on('exit',()=>{try{server.kill('SIGKILL')}catch{/* already exited */}});
await new Promise((resolve,reject)=>{server.stdout.on('data',chunk=>{if(String(chunk).includes('ready'))resolve()});server.on('exit',code=>reject(Error('Server exited '+code)))});
const browser=await chromium.launch({executablePath:process.env.AIW_BROWSER_EXECUTABLE,headless:true});
const errors=[];
try{
 const page=await browser.newPage({viewport:{width:1440,height:900}});
 page.on('pageerror',e=>errors.push(e.message));
 await page.goto('http://127.0.0.1:'+port+'/?chapter=7&tab=work&object=tr-002&product=mysql',{waitUntil:'networkidle'});
 await page.locator('.tr-product-arrival').waitFor();
 assert.match(await page.locator('.tr-product-arrival').innerText(),/MySQL/);
 assert.match(await page.locator('.tr-driver-matrix').innerText(),/PostgreSQL|MongoDB/);
 const before=await page.evaluate(()=>JSON.stringify(window.aiwProjectStore.value.document));
 await page.click('.tr-product-arrival [data-tr-action="add-library"]');
 assert.equal(await page.locator('#tr-option-form [name="product"]').inputValue(),'MySQL');
 await page.click('.tr-dialog [data-tr-action="close"]');
 assert.equal(await page.evaluate(()=>JSON.stringify(window.aiwProjectStore.value.document)),before,'opening a library product must not create or prefer an option');
 const current=await page.locator('.tr-sensitivity [name="sensitivityDriver"]').inputValue();
 assert.ok(current,'a linked scenario is available for sensitivity');
 const priority=await page.evaluate(id=>window.aiwProjectStore.value.document.quality.drivers.find(d=>d.id===id)?.priority,current);
 await page.selectOption('.tr-sensitivity [name="sensitivityPriority"]',priority==='Low'?'High':'Low');
 await page.click('.tr-sensitivity [data-tr-action="sensitivity"]');
 await page.waitForFunction(()=>document.querySelector('.tr-sensitivity-result')?.textContent?.includes('branch touches')||document.querySelector('.tr-sensitivity-result')?.querySelector('.l-error'),null,{timeout:10000});
 assert.match(await page.locator('.tr-sensitivity-result').innerText(),/No product is preferred or recorded/i);
 assert.match(await page.locator('.tr-sensitivity-result').innerText(),/cannot establish target attainment/i);
 assert.ok(await page.locator('.tr-scenario-options article').count()>=2,'both option judgements are in the scenario reading');
 assert.ok(await page.locator('.tr-affected a').count()>=2,'affected records have exact chapter links');
 await page.locator('.tr-review-plan summary').click();
 assert.ok(await page.locator('.tr-review-plan [data-tr-action="assess"]').count()>=2,'the review plan uses the existing judgement editor');
 assert.match(await page.locator('.tr-review-plan').innerText(),/Chapter 2[\s\S]*Validate/i);
 const targetPage=await browser.newPage();
 const targetHref=await page.locator('.tr-decision-brief .tr-brief-targets a').filter({hasText:'QD-002'}).getAttribute('href');
 await targetPage.goto(new URL(targetHref,page.url()).href,{waitUntil:'networkidle'});
 assert.equal(new URL(targetPage.url()).searchParams.get('object'),'QD-002','the target link selects its exact Chapter 2 driver through canonical object identity');
 const reviewHref=await page.locator('.tr-review-plan a').first().getAttribute('href');
 await targetPage.goto(new URL(reviewHref,page.url()).href,{waitUntil:'networkidle'});
 assert.equal(new URL(targetPage.url()).searchParams.get('object'),current,'review plan opens the explored driver in Chapter 2 Work');
 await targetPage.close();
 assert.equal(await page.evaluate(()=>JSON.stringify(window.aiwProjectStore.value.document)),before,'temporary branch must not mutate the project');
 await page.selectOption('.tr-sensitivity [name="sensitivityDriver"]','QD-002');
 await page.fill('.tr-sensitivity [name="sensitivityTarget"]','99.99');
 await page.click('.tr-sensitivity [data-tr-action="sensitivity"]');
 await page.waitForFunction(()=>document.querySelector('.tr-branch-changes')?.textContent?.includes('99.99'));
 assert.match(await page.locator('.tr-branch-changes').innerText(),/99\.9 → 99\.99 %/);
 assert.match(await page.locator('.tr-sensitivity-result').innerText(),/cannot establish target attainment/i);
 assert.equal(await page.evaluate(()=>JSON.stringify(window.aiwProjectStore.value.document)),before,'a stricter availability target remains hypothetical');
 const oldCount=await page.evaluate(()=>window.aiwProjectStore.value.document.technologyRealisation.records.find(r=>r.id==='tr-002').options.length);
 await page.click('.tr-product-arrival [data-tr-action="add-library"]');
 await page.fill('#tr-option-form [name="version"]','8.4');
 await page.fill('#tr-option-form [name="serviceTier"]','Community edition, design assumption');
 await page.selectOption('#tr-option-form [name="operatingModel"]','Self managed');
 await page.fill('#tr-option-form [name="topology"]','Primary and standby across two failure domains, to verify');
 await page.click('#tr-option-form [type="submit"]');
 await page.locator('.tr-dialog .wb-review-step').waitFor();
 await page.check('.tr-dialog .wb-review-step [data-reviewed]');
 await page.fill('.tr-dialog .wb-review-step [name="reason"]','Synthetic browser test of an explicitly reviewed MySQL option.');
 await page.click('.tr-dialog .wb-review-step [data-wb-action="apply-preview"]');
 await page.waitForFunction(expected=>window.aiwProjectStore.value.document.technologyRealisation.records.find(r=>r.id==='tr-002').options.length===expected,oldCount+1);
 const saved=await page.evaluate(()=>{const r=window.aiwProjectStore.value.document.technologyRealisation.records.find(r=>r.id==='tr-002');return {selected:r.selectedOptionId,option:r.options.at(-1)}});
 assert.equal(saved.option.product,'MySQL');
 assert.equal(saved.selected,null,'adding a product option cannot silently choose it');
 assert.equal(saved.option.serviceTier,'Community edition, design assumption');
 const catalogueUse=await page.evaluate(async()=>{const {findTechnologyProduct}=await import('/technology-catalogue.js');return findTechnologyProduct(window.aiwProjectStore.value.document,'mysql')?.uses.find(u=>u.optionId===window.aiwProjectStore.value.document.technologyRealisation.records.find(r=>r.id==='tr-002').options.at(-1).id)});
 assert.equal(catalogueUse?.realizationId,'tr-002');
 assert.equal(catalogueUse?.status,'Candidate option');
 assert.deepEqual(errors,[]);
 await page.goto('http://127.0.0.1:'+port+'/?chapter=7&tab=work&object=tr-003',{waitUntil:'networkidle'});
 await page.click('[data-tr-stage="compare"]');
 const kafka=page.locator('.tr-option').filter({hasText:'Apache Kafka'});
 await kafka.locator('.tr-product-profile summary').click();
 assert.match(await kafka.locator('.tr-source-mismatch').innerText(),/3\.9[\s\S]*4\.3[\s\S]*Verify applicability/,'versioned documentation cannot silently support a different option release');
 assert.ok(await kafka.locator('.tr-source-mismatch').isVisible(),'release mismatch is visible at the point of choice');
 const mobile=await browser.newPage({viewport:{width:390,height:844}});
 await mobile.goto('http://127.0.0.1:'+port+'/?chapter=7&tab=work&object=tr-002&product=mysql',{waitUntil:'networkidle'});
 await mobile.locator('.tr-driver-matrix').waitFor();
 // rc39/rc40 (rc41 W4): the comparison draws two scrolling matrices — the driver matrix and "Decision weighing" — so the
 // driver matrix's own is named (exactly one) and every matrix on the page must fit the phone without widening it.
 assert.equal(await mobile.locator('.tr-driver-matrix .tr-matrix-scroll').count(),1);
 const bounds=await mobile.locator('.tr-matrix-scroll').evaluateAll(xs=>xs.map(e=>({width:e.getBoundingClientRect().width,viewport:innerWidth,scrollable:e.scrollWidth>e.clientWidth,pageOverflow:document.documentElement.scrollWidth>innerWidth})));
 assert.ok(bounds.length>=1&&bounds.every(b=>b.width<=b.viewport+1&&!b.pageOverflow),JSON.stringify(bounds));
 assert.match(await mobile.locator('.tr-driver-matrix tbody td .tr-matrix-option').first().innerText(),/PostgreSQL|MongoDB/,'narrow layout names the option above its judgement in accessible text');
 console.log('PASS Chapter 7 technology choices: aligned comparisons, version warning, navigable review scenario, no silent mutation and mobile judgement cards.');
}finally{await browser.close();server.kill();try{rmSync(db,{force:true})}catch{/* test scratch cleanup */}}
