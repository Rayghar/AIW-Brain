import assert from 'node:assert/strict';
import {Window} from 'happy-dom';
import {capturePanelPlace,restorePanelPlace,mountPanelResize} from './public/brain-panel-state.js';
const w=new Window({width:1440,height:900,url:'https://aiw.test/'});
for(const key of ['window','document','localStorage','KeyboardEvent'])Object.defineProperty(globalThis,key,{value:key==='window'?w:w[key],configurable:true});
const panel=document.createElement('aside');document.body.append(panel);
const html='<div data-brain-resize tabindex="0"></div><div class="brain-content"><details><summary>Recorded sources</summary><p>Exact receipts</p></details><textarea data-intel-prompt>Keep this question</textarea><div data-proposals></div></div>';
panel.innerHTML=html;panel.dataset.placeKey='project-a:1:req-1';
panel.querySelector('details').open=true;
panel.querySelector('.brain-content').scrollTop=317;
const input=panel.querySelector('textarea');input.focus();input.setSelectionRange(5,9);
panel.querySelector('[data-proposals]').__view={scope:'selected',query:'quality',shown:12};
const place=capturePanelPlace(panel,'project-a:1:req-1');
panel.innerHTML=html;
restorePanelPlace(panel,'project-a:1:req-1',place);
assert.equal(panel.querySelector('.brain-content').scrollTop,317);
assert.equal(panel.querySelector('details').open,true);
assert.equal(document.activeElement,panel.querySelector('textarea'));
assert.deepEqual([document.activeElement.selectionStart,document.activeElement.selectionEnd],[5,9]);
assert.equal(panel.querySelector('[data-proposals]').__view.query,'quality');
assert.equal(capturePanelPlace(panel,'project-b:1:req-1'),null,'another project cannot inherit the old position or filters');
panel.innerHTML=html;restorePanelPlace(panel,'project-b:1:req-1',place);
assert.equal(panel.querySelector('details').open,false);
assert.equal(panel.querySelector('[data-proposals]').__view,undefined);
mountPanelResize(panel,'project-b:brain-width');
const handle=panel.querySelector('[data-brain-resize]');
handle.dispatchEvent(new KeyboardEvent('keydown',{key:'ArrowLeft',bubbles:true,cancelable:true}));
assert.equal(handle.getAttribute('aria-valuenow'),'512');
assert.equal(localStorage.getItem('project-b:brain-width'),'512');
handle.dispatchEvent(new KeyboardEvent('keydown',{key:'Home',bubbles:true,cancelable:true}));
assert.equal(handle.getAttribute('aria-valuenow'),'360');
handle.dispatchEvent(new KeyboardEvent('keydown',{key:'End',bubbles:true,cancelable:true}));
assert.equal(handle.getAttribute('aria-valuenow'),'760');
assert.equal(document.documentElement.style.getPropertyValue('--brain-pane-width'),'760px');
await w.happyDOM.close();
console.log('PASS: panel redraw retains focus, caret, scroll, disclosures and proposal filters only for the same context; keyboard resize updates accessible bounds and preference.');
