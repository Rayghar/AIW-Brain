// Build public/brain-tradeoffs.js, AIW's trade-off catalogue and reference latency figures (AIW-TRADEOFFS-1), from
// knowledge/brain-tradeoffs.json: every passage and figure gets the SHA-256 of its text, each attribution key becomes
// the source it names (title, url, licence), and the pack gets one hash over all of them. The JSON is the source a
// person edits; the module is what the browser and the server load. brain-tradeoffs-validate.mjs recomputes the hashes
// from the module's own text and asserts parity with this JSON, so neither can drift from the other.
// Run: node scripts/build-brain-tradeoffs.mjs
import {readFileSync, writeFileSync} from 'node:fs';
import {createHash} from 'node:crypto';

const sha256 = text => createHash('sha256').update(text, 'utf8').digest('hex');
const here = new URL('.', import.meta.url);
const source = JSON.parse(readFileSync(new URL('../knowledge/brain-tradeoffs.json', here), 'utf8'));
const WORDS = [120, 220];

const attribution = keys => keys.map(k => { const s = source.sources[k]; if (!s) throw Error('Unknown source ' + k); return {title: s.title, url: s.url, licence: s.licence}; });
const passages = source.passages.map(x => {
  const words = x.text.trim().split(/\s+/).length;
  if (words < WORDS[0] || words > WORDS[1]) throw Error(`${x.id} is ${words} words; a trade-off passage is ${WORDS[0]}–${WORDS[1]}.`);
  if (!/^TO-\d{3}$/.test(x.id) || !x.title || !x.chapters?.length || !x.records?.length || !Array.isArray(x.cues) || x.cues.some(c => typeof c !== 'string' || !c.trim())) throw Error(`${x.id} needs an id, a title, chapters, record kinds and cue words.`);
  // The cues are the words a question uses for this trade-off (retrieval matches them like the title); the hash covers the text.
  return {id: x.id, title: x.title, cues: x.cues, text: x.text.trim(), chapters: x.chapters, records: x.records, sha256: sha256(x.text.trim()), attribution: attribution(x.attribution)};
});
const figures = source.figures.map(x => {
  if (!/^LN-\d{3}$/.test(x.id) || !Number.isFinite(x.value) || x.unit !== 'ns' || !x.text) throw Error(`${x.id} needs an id, a value in ns and a reading.`);
  return {id: x.id, title: x.title, value: x.value, unit: x.unit, text: x.text.trim(), sha256: sha256(x.text.trim()), attribution: attribution(x.attribution)};
});
if (new Set([...passages, ...figures].map(x => x.id)).size !== passages.length + figures.length) throw Error('Duplicate id.');
const pack = {id: source.id, authored: source.authored, title: source.title, authority: source.authority, figuresNote: source.figuresNote, sha256: sha256([...passages, ...figures].map(x => x.id + ':' + x.sha256).join('\n')), passages, figures};
const out = `// AIW's trade-off catalogue and reference latency figures (${pack.id}): ${passages.length} trade-off passages and ${figures.length} figures,
// written by AIW in its own words and attributed to the sources whose lists they follow. Generated by
// scripts/build-brain-tradeoffs.mjs from knowledge/brain-tradeoffs.json; edit the JSON, not this file. A brain-method
// source for retrieval (architecture-brain.js) with a receipt per passage; named in the withdraw list
// (knowledge-governance.js); never scoring, never a constraint, never conformance.
export const BRAIN_TRADEOFFS = ${JSON.stringify(pack)};
`;
writeFileSync(new URL('../public/brain-tradeoffs.js', here), out);
console.log('brain-tradeoffs', passages.length, 'passages', figures.length, 'figures', Buffer.byteLength(out), 'bytes', pack.sha256);
