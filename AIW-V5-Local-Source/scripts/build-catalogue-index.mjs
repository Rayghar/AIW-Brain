// Build public/catalogue-index.js: the pattern catalogue's names, kinds and declared relations,
// small enough for the chapter models to link recorded patterns to it without loading the
// full catalogue. Each record's hash (recordHashes) lets a catalogue receipt be checked without it too (round 2,
// I2-20: the full catalogue loads only when the Brain or the knowledge view needs it).
// Run: node scripts/build-catalogue-index.mjs
import {writeFileSync} from 'node:fs';
import {BRAIN_CATALOGUE} from '../public/brain-catalogue.js';
const records = BRAIN_CATALOGUE.records.map(r => ({id: r.id, name: r.name, type: r.recordType, aliases: (r.aliases || []).filter(a => a && a.toLowerCase() !== r.name.toLowerCase()).slice(0, 4), conflicts: r.conflicts || [], alternatives: r.alternatives || []}));
// Each record's SHA-256, base64url (43 characters), concatenated in record order: compact enough for every page.
const hashes = BRAIN_CATALOGUE.records.map(r => Buffer.from(r.recordSha256, 'hex').toString('base64url')).join('');
if (hashes.length !== records.length * 43) throw Error('A record hash is not a SHA-256.');
const out = `// The pattern catalogue's names, kinds and declared relations, indexed from brain-catalogue.js
// (${BRAIN_CATALOGUE.releaseId}). Generated by scripts/build-catalogue-index.mjs; descriptive only.
export const CATALOGUE = {releaseId: ${JSON.stringify(BRAIN_CATALOGUE.releaseId)}, sourceSha256: ${JSON.stringify(BRAIN_CATALOGUE.sourceSha256)}, records: ${JSON.stringify(records)}, recordHashes: ${JSON.stringify(hashes)}};
`;
writeFileSync(new URL('../public/catalogue-index.js', import.meta.url), out);
console.log('catalogue index', records.length, 'records', out.length, 'bytes');
